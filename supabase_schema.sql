-- ========================================================
-- Supabase Schema for Hirrd Job Portal
-- Run this in your Supabase Project -> SQL Editor
-- ========================================================

-- 1. Create Companies Table
CREATE TABLE IF NOT EXISTS public.companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    logo_url TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create Jobs Table
CREATE TABLE IF NOT EXISTS public.jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    location TEXT NOT NULL,
    company_id BIGINT REFERENCES public.companies(id) ON DELETE CASCADE,
    requirements TEXT NOT NULL,
    recruiter_id TEXT NOT NULL,
    "isOpen" BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create Applications Table
CREATE TABLE IF NOT EXISTS public.applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT REFERENCES public.jobs(id) ON DELETE CASCADE,
    candidate_id TEXT NOT NULL,
    name TEXT NOT NULL,
    status TEXT DEFAULT 'applied',
    experience INTEGER NOT NULL,
    skills TEXT NOT NULL,
    education TEXT NOT NULL,
    resume TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Create Saved Jobs Table
CREATE TABLE IF NOT EXISTS public.saved_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    job_id BIGINT REFERENCES public.jobs(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(user_id, job_id)
);

-- ========================================================
-- 5. Storage Buckets Setup
-- ========================================================
INSERT INTO storage.buckets (id, name, public)
VALUES 
    ('company-logo', 'company-logo', true),
    ('resumes', 'resumes', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Full Access to 'company-logo' (Select, Insert, Update, Delete)
DROP POLICY IF EXISTS "Give public full access to company-logo" ON storage.objects;
DROP POLICY IF EXISTS "Allow Public Read on company-logo" ON storage.objects;
DROP POLICY IF EXISTS "Allow Upload to company-logo" ON storage.objects;
DROP POLICY IF EXISTS "Allow Update on company-logo" ON storage.objects;

CREATE POLICY "Give public full access to company-logo"
ON storage.objects FOR ALL
TO public
USING (bucket_id = 'company-logo')
WITH CHECK (bucket_id = 'company-logo');

-- Full Access to 'resumes' (Select, Insert, Update, Delete)
DROP POLICY IF EXISTS "Give public full access to resumes" ON storage.objects;
DROP POLICY IF EXISTS "Allow Public Read on resumes" ON storage.objects;
DROP POLICY IF EXISTS "Allow Upload to resumes" ON storage.objects;
DROP POLICY IF EXISTS "Allow Update on resumes" ON storage.objects;

CREATE POLICY "Give public full access to resumes"
ON storage.objects FOR ALL
TO public
USING (bucket_id = 'resumes')
WITH CHECK (bucket_id = 'resumes');

-- ========================================================
-- 6. Table Row Level Security (RLS) Policies
-- ========================================================
ALTER TABLE public.companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saved_jobs ENABLE ROW LEVEL SECURITY;

-- Companies Policies
DROP POLICY IF EXISTS "Allow all on companies" ON public.companies;
DROP POLICY IF EXISTS "Allow all to read companies" ON public.companies;
DROP POLICY IF EXISTS "Allow authenticated to insert companies" ON public.companies;
CREATE POLICY "Allow all on companies" ON public.companies FOR ALL TO public USING (true) WITH CHECK (true);

-- Jobs Policies
DROP POLICY IF EXISTS "Allow all on jobs" ON public.jobs;
DROP POLICY IF EXISTS "Allow all to read jobs" ON public.jobs;
DROP POLICY IF EXISTS "Allow authenticated to insert jobs" ON public.jobs;
DROP POLICY IF EXISTS "Allow recruiters to update jobs" ON public.jobs;
DROP POLICY IF EXISTS "Allow recruiters to delete jobs" ON public.jobs;
CREATE POLICY "Allow all on jobs" ON public.jobs FOR ALL TO public USING (true) WITH CHECK (true);

-- Applications Policies
DROP POLICY IF EXISTS "Allow all on applications" ON public.applications;
DROP POLICY IF EXISTS "Allow users to read applications" ON public.applications;
DROP POLICY IF EXISTS "Allow candidates to insert applications" ON public.applications;
DROP POLICY IF EXISTS "Allow recruiters to update applications" ON public.applications;
CREATE POLICY "Allow all on applications" ON public.applications FOR ALL TO public USING (true) WITH CHECK (true);

-- Saved Jobs Policies
DROP POLICY IF EXISTS "Allow all on saved_jobs" ON public.saved_jobs;
DROP POLICY IF EXISTS "Allow users to read saved jobs" ON public.saved_jobs;
DROP POLICY IF EXISTS "Allow users to insert saved jobs" ON public.saved_jobs;
DROP POLICY IF EXISTS "Allow users to delete saved jobs" ON public.saved_jobs;
CREATE POLICY "Allow all on saved_jobs" ON public.saved_jobs FOR ALL TO public USING (true) WITH CHECK (true);
